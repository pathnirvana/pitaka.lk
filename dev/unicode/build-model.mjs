// Builds tools/unicode/lib/sinhala-model.js: how likely each character is after another in Sinhala text, from the
// pitaka.lk books. detect.js uses it to tell which encoding turns a text into real Sinhala.
//   node dev/unicode/build-model.mjs
import fs from 'node:fs'
import path from 'node:path'
import { bookWords } from './corpus.mjs'

const N = 131 // 0 other, 1 space, 2 ZWJ, 3.. U+0D80-0DFF
const sym = (c) => c === ' ' ? 1 : c === '‍' ? 2 : c >= '඀' && c <= '෿' ? 3 + c.charCodeAt(0) - 0x0D80 : 0
const counts = Array.from({ length: N }, () => new Float64Array(N))
for (const [w, c] of bookWords({ maxFiles: 100000 })) {
    let prev = 1
    for (const ch of w + ' ') { const s = sym(ch); counts[prev][s] += c; prev = s }
}
// cost = -log2 P(next | prev) with add-one smoothing, in half bits, capped to one base-36 digit
let table = ''
for (let a = 0; a < N; a++) {
    const total = counts[a].reduce((x, y) => x + y, 0) + N
    for (let b = 0; b < N; b++) table += Math.min(35, Math.round(-Math.log2((counts[a][b] + 1) / total) * 2)).toString(36)
}
const out = path.resolve(import.meta.dirname, '../../tools/unicode/lib/sinhala-model.js')
fs.writeFileSync(out, `// Generated by dev/unicode/build-model.mjs - do not edit.
// Cost of each character after another in Sinhala text, in half bits (-2 log2 P), one base-36 digit per pair.
// Symbols: 0 other, 1 space, 2 ZWJ, 3 + (code - 0x0D80) for the Sinhala block.
export const N = ${N}
export const table = '${table}'
`)
console.log(out, table.length)
